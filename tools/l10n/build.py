#!/usr/bin/env python3
"""Build Gearforge's string tables.

    python3 tools/l10n/build.py            # write the four .strings files, report coverage
    python3 tools/l10n/build.py --strict   # same, but exit 1 if any Russian string is missing or invalid
    python3 tools/l10n/build.py --check    # validate only, write nothing (implies --strict)

Inputs:  tools/l10n/extract.py (keys + English, scanned from the sources) and tools/l10n/ru.json (translations).
Outputs: App/Resources/{en,ru}.lproj/{Localizable,GameData}.strings — UTF-8, `"key" = "value";`, sorted.

Checks: missing Russian keys, stale ru.json keys (no longer in the sources), empty translations, format-specifier
parity between English and Russian (same specifiers, same order), and a round trip of every written file.
"""
from __future__ import annotations

import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import extract  # noqa: E402

ROOT = extract.ROOT
RU_JSON = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ru.json")
RES = os.path.join(ROOT, "App", "Resources")
SPEC = re.compile(r"%(?:\d+\$)?(?:lld|ld|d|@|%)")

HEADERS = {
    "Localizable": "UI strings — key = English text. GENERATED by tools/l10n/build.py: edit tools/l10n/ru.json "
                   "(or the Swift sources) and re-run; do not edit by hand.",
    "GameData": "Game content names and campaign text (item.<id>, tech.<id>, level.<L>.title, ...). GENERATED by "
                "tools/l10n/build.py: edit tools/l10n/ru.json (or GameData.json / Levels.swift) and re-run.",
}


# ------------------------------------------------------------------------------------------- .strings I/O

def escape(s: str) -> str:
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t").replace("\r", "\\r")


_UNESC = {"\\": "\\", '"': '"', "n": "\n", "t": "\t", "r": "\r"}


def unescape(s: str) -> str:
    return re.sub(r"\\(.)", lambda m: _UNESC.get(m.group(1), m.group(1)), s)


def render(table: dict, header: str) -> str:
    lines = ["/* %s */" % header, ""]
    lines += ['"%s" = "%s";' % (escape(k), escape(v)) for k, v in sorted(table.items())]
    return "\n".join(lines) + "\n"


ENTRY = re.compile(r'^"((?:[^"\\]|\\.)*)"\s*=\s*"((?:[^"\\]|\\.)*)";$')


def parse(text: str) -> dict:
    """Parse a .strings file written by render(). Raises on anything unexpected."""
    out: dict[str, str] = {}
    body = re.sub(r"/\*.*?\*/", "", text, flags=re.S)
    for n, line in enumerate(body.splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        m = ENTRY.match(line)
        if not m:
            raise ValueError("unparseable line %d: %r" % (n, line))
        k = unescape(m.group(1))
        if k in out:
            raise ValueError("duplicate key %r" % k)
        out[k] = unescape(m.group(2))
    return out


def specifiers(s: str) -> list[str]:
    return SPEC.findall(s)


# ------------------------------------------------------------------------------------------- build

def main(argv: list[str]) -> int:
    check_only = "--check" in argv
    strict = "--strict" in argv or check_only

    src = extract.extract()
    ui_keys: list[str] = src["ui"]
    data_en: dict[str, str] = src["data"]
    ru = json.load(open(RU_JSON, encoding="utf-8"))
    ru_ui: dict[str, str] = ru.get("ui", {})
    ru_data: dict[str, str] = ru.get("data", {})

    tables_en = {"Localizable": {k: k for k in ui_keys}, "GameData": dict(data_en)}
    tables_ru: dict[str, dict] = {"Localizable": {}, "GameData": {}}
    missing: list[str] = []
    errors: list[str] = []

    for name, en_table, ru_src in (("Localizable", tables_en["Localizable"], ru_ui),
                                   ("GameData", tables_en["GameData"], ru_data)):
        for k, en in en_table.items():
            if k not in ru_src:
                missing.append("%s: %s" % (name, k))
                continue
            v = ru_src[k]
            if not isinstance(v, str) or not v.strip():
                errors.append("%s: empty translation for %r" % (name, k))
                continue
            if specifiers(en) != specifiers(v):
                errors.append("%s: format specifiers differ for %r: en %s, ru %s"
                              % (name, k, specifiers(en), specifiers(v)))
                continue
            tables_ru[name][k] = v

    stale = ["ui: " + k for k in sorted(set(ru_ui) - set(ui_keys))] + \
            ["data: " + k for k in sorted(set(ru_data) - set(data_en))]

    # Write + round trip.
    for lang, tables in (("en", tables_en), ("ru", tables_ru)):
        for name, table in tables.items():
            text = render(table, HEADERS[name])
            path = os.path.join(RES, "%s.lproj" % lang, "%s.strings" % name)
            if not check_only:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
                text = open(path, encoding="utf-8").read()
            try:
                back = parse(text)
            except ValueError as e:
                errors.append("%s/%s.strings: %s" % (lang, name, e))
                continue
            if back != table:
                errors.append("%s/%s.strings: round trip mismatch" % (lang, name))

    # Report.
    n_ui, n_data = len(ui_keys), len(data_en)
    ru_ui_n, ru_data_n = len(tables_ru["Localizable"]), len(tables_ru["GameData"])
    total = n_ui + n_data
    done = ru_ui_n + ru_data_n
    print("UI keys:   %4d   ru %4d (%.1f%%)" % (n_ui, ru_ui_n, 100.0 * ru_ui_n / max(1, n_ui)))
    print("Data keys: %4d   ru %4d (%.1f%%)" % (n_data, ru_data_n, 100.0 * ru_data_n / max(1, n_data)))
    print("Total:     %4d   ru %4d (%.1f%%)" % (total, done, 100.0 * done / max(1, total)))
    if not check_only:
        print("Wrote App/Resources/{en,ru}.lproj/{Localizable,GameData}.strings")
    if missing:
        print("\nMissing Russian (%d) — add to tools/l10n/ru.json:" % len(missing))
        for m in missing:
            print("  " + m)
    if stale:
        print("\nStale ru.json keys (%d) — no longer in the sources, not written:" % len(stale))
        for s in stale:
            print("  " + s)
    if errors:
        print("\nErrors (%d):" % len(errors))
        for e in errors:
            print("  " + e)
    issues = extract.needs_code_change()
    if issues:
        print("\nNeeds code change (%d) — not localisable as written, see docs/team/localization.md" % len(issues))
    if errors or (strict and missing):
        print("\nFAILED")
        return 1
    print("\nOK")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
