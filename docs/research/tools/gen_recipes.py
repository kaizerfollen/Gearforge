#!/usr/bin/env python3
"""Generate docs/research/02_recipes.md from raw.json (Factorio 1.1.110, NORMAL recipe difficulty)."""
import sys, os
sys.path.insert(0, os.path.dirname(__file__))
from gf_common import *

raw = load_raw(sys.argv[1])
OUT = sys.argv[2]
R = raw['recipe']
items = all_items(raw)
prod_limit = set(raw['module']['productivity-module']['limitation'])
char_cats = set(raw['character']['character']['crafting_categories'])

unlocked_by = {}
for tn, t in raw['technology'].items():
    for e in t.get('effects', []) or []:
        if e.get('type') == 'unlock-recipe':
            unlocked_by.setdefault(e['recipe'], []).append(tn)

machines_for = {}
for t in ('assembling-machine', 'furnace', 'rocket-silo'):
    for n, m in raw.get(t, {}).items():
        for c in m.get('crafting_categories', []):
            machines_for.setdefault(c, []).append(n)
machines_for['crafting'] = machines_for.get('crafting', []) + ['character']

def norm(r):
    rr = dict(r)
    if r.get('normal'):
        rr.update(r['normal'])
    ings = ingr_list(rr.get('ingredients'))
    if rr.get('results'):
        res = ingr_list(rr['results'])
    else:
        res = [{'type': 'item', 'name': rr['result'], 'amount': rr.get('result_count', 1)}]
    return rr, ings, res

def fmt_stack(lst, is_result=False):
    parts = []
    for x in lst:
        nm = gid(x['name'])
        amt = x.get('amount')
        if amt is None:
            amt = f"{x.get('amount_min')}-{x.get('amount_max')}"
        s = f"{num(amt) if not isinstance(amt, str) else amt} {nm}"
        if x.get('type') == 'fluid':
            s += ' (fluid'
            if x.get('temperature') is not None:
                s += f", {x['temperature']}°C"
            if x.get('minimum_temperature') is not None:
                s += f", min {x['minimum_temperature']}°C"
            s += ')'
        if is_result and x.get('probability') is not None and x['probability'] != 1:
            s += f" @ p={num(x['probability'])} ({num(x['probability'] * 100)}%)"
        parts.append(s)
    return ' + '.join(parts)

CAT_ORDER = ['smelting', 'crafting', 'advanced-crafting', 'crafting-with-fluid', 'oil-processing', 'chemistry',
             'centrifuging', 'rocket-building']
rows = {c: [] for c in CAT_ORDER}
count = 0
excluded = []
for n, r in sorted(R.items(), key=lambda kv: (kv[1].get('subgroup', ''), kv[1].get('order', ''), kv[0])):
    rr, ings, res = norm(r)
    if n in EDITOR_ONLY:
        excluded.append(n)
        continue
    cat = rr.get('category', 'crafting')
    has_fluid = any(x.get('type') == 'fluid' for x in ings + res)
    handcraft = cat in char_cats and not has_fluid
    enabled = rr.get('enabled', True) is not False
    time = rr.get('energy_required', 0.5)
    main = res[0]['name'] if len(res) == 1 else None
    techs = unlocked_by.get(n, [])
    ph = recipe_phase(raw, n)
    notes = []
    if rr.get('hidden'):
        notes.append('hidden (machine-internal)')
    if n.startswith('fill-') or n.startswith('empty-'):
        notes.append('barreling')
    if main is None and len(res) > 1:
        notes.append('multi-output')
    rows[cat].append([gid(n), display(n) if main is None or gid(main) != gid(n) else display(main), num(time),
                      fmt_stack(ings), fmt_stack(res, True), 'yes' if handcraft else 'no',
                      'yes' if n in prod_limit else 'no', 'yes' if enabled else 'no',
                      ', '.join(tech_id(t) for t in techs) or ('(start)' if enabled else '-'), ph, '; '.join(notes)])
    count += 1

lines = ['# 02 — Recipes (Gearforge base set)\n']
lines.append('Source: Factorio 1.1.110 `base/prototypes/recipe.lua` (+ auto-generated barrel recipes from `data-updates.lua`), NORMAL difficulty values (expensive mode ignored). Generated by `docs/research/tools/gen_recipes.py`.\n')
lines.append('## Column meanings\n')
lines.append('- **time s** – `energy_required` in seconds at crafting speed 1. Real time = time / (machine crafting speed × (1 + speed bonuses)). Default 0.5 s when unspecified.')
lines.append('- **ingredients / results** – amounts per craft. Fluids are marked `(fluid)` (units). Probabilistic results: `@ p=` is the chance that the result is produced on each craft (amount is fixed when it is produced).')
lines.append('- **hand** – handcraftable by the character: category `crafting` AND no fluid ingredient/result. Note: the character can handcraft any `crafting` recipe even if a machine-only intermediate is required, as long as all its intermediates are themselves handcraftable (see 05_mechanics §Handcrafting).')
lines.append('- **prod** – productivity modules allowed (recipe is in the productivity-module limitation whitelist).')
lines.append('- **start** – enabled at game start (no tech needed). **unlocked by** – technology id(s) that unlock it.')
lines.append('- **phase** – see 01_items conventions.\n')

lines.append('## Crafting categories → machines\n')
cat_rows = []
for c in CAT_ORDER + ['basic-crafting']:
    cat_rows.append([c, ', '.join(gid(m) for m in machines_for.get(c, []))])
lines.append(md_table(['category', 'machines that can craft it'], cat_rows))
lines.append('\nNote: `basic-crafting` exists in 1.1 but no base recipe uses it. `crafting-with-fluid` needs a fluid box, so assembler 1 (no fluid box) cannot do it. Furnaces (`smelting`) auto-select their recipe from the input item.\n')

for c in CAT_ORDER:
    if not rows[c]:
        continue
    lines.append(f'## Category `{c}` ({len(rows[c])})\n')
    lines.append(md_table(['id', 'display name', 'time s', 'ingredients', 'results', 'hand', 'prod', 'start', 'unlocked by', 'phase', 'notes'], rows[c]))
    lines.append('')

lines.append('## Excluded recipes\n')
lines.append(', '.join(excluded) + ' (hidden editor loaders).\n')
lines.append('## Recipes that are NOT recipes (special production)\n')
lines.append('- **orbital_card** (space science pack) is not crafted: launching a rocket that carries a **satellite** yields 1000 orbital cards in the silo output slot.')
lines.append('- **rocket**: the silo crafts 100 × `rocket_part` (recipe above, category `rocket-building`); when 100 parts are done the rocket is assembled, the satellite (inserted into the rocket inventory) is loaded, and launch happens automatically if "auto-launch" is on or manually by button. Launching any rocket = victory in campaign final level.')
lines.append('- Mining products (ores, coal, stone, crude oil, wood) come from resources/trees — see 01_items §Raw resources and 05_mechanics §Mining.\n')
lines.append(f'**Total recipes listed: {count}** (all phases).\n')

with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
print('recipes', count, {c: len(v) for c, v in rows.items()})
