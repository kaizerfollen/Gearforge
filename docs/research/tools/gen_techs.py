#!/usr/bin/env python3
"""Generate docs/research/04_technologies.md from raw.json (Factorio 1.1.110, normal mode)."""
import sys, os, re
sys.path.insert(0, os.path.dirname(__file__))
from gf_common import *

raw = load_raw(sys.argv[1])
OUT = sys.argv[2]
T = raw['technology']

def unit(t):
    u = t.get('normal', {}).get('unit') if t.get('normal') else t['unit']
    return u

def techdata(t):
    d = dict(t)
    if t.get('normal'):
        d.update(t['normal'])
    return d

def ingr(u):
    out = []
    for i in u['ingredients']:
        n, a = (i[0], i[1]) if isinstance(i, list) else (i['name'], i['amount'])
        out.append((n, a))
    return out

PACK_SHORT = {'automation-science-pack': 'R', 'logistic-science-pack': 'G', 'military-science-pack': 'K',
              'chemical-science-pack': 'B', 'production-science-pack': 'P', 'utility-science-pack': 'Y',
              'space-science-pack': 'W'}

def fmt_effect(e):
    ty = e['type']
    if ty == 'unlock-recipe':
        return None
    m = e.get('modifier')
    if ty in ('ammo-damage', 'gun-speed'):
        return f"{ty} [{e.get('ammo_category')}] +{num(m * 100)}%"
    if ty == 'turret-attack':
        return f"turret-attack [{e.get('turret_id')}] +{num(m * 100)}%"
    if isinstance(m, (int, float)) and ty in ('mining-drill-productivity-bonus', 'laboratory-speed', 'worker-robot-speed',
                                              'worker-robot-battery', 'train-braking-force-bonus', 'laboratory-productivity',
                                              'character-mining-speed', 'artillery-range', 'manual-crafting-speed'):
        return f"{ty} +{num(m * 100)}%"
    if ty == 'nothing':
        return f"(description only: {e.get('effect_description')})"
    if ty == 'give-item':
        return f"give {e.get('count', 1)} {gid(e['item'])}"
    return f"{ty} {'+' if isinstance(m, (int, float)) and m >= 0 else ''}{num(m) if m is not None else ''}".strip()

rocket_req = rocket_closure(raw)

def tech_phase(n, t):
    return tech_phase_of(raw, n, rocket_req)

rows = []
inf_rows = []
by_base = {}
for n, t0 in T.items():
    t = techdata(t0)
    u = unit(t)
    m = re.match(r'^(.*)-(\d+)$', n)
    base = m.group(1) if m else n
    by_base.setdefault(base, []).append(n)

def sort_key(kv):
    n, t = kv
    return (len(ingr(unit(techdata(t)))), unit(techdata(t)).get('count') or 0, n)

order_list = sorted(T.items(), key=sort_key)
for n, t0 in order_list:
    t = techdata(t0)
    u = unit(t)
    packs = ingr(u)
    cost_packs = ' + '.join(f"{a} {gid(p)}" for p, a in packs)
    short = ''.join(PACK_SHORT[p] for p, a in packs)
    count = u.get('count')
    formula = u.get('count_formula')
    recs = [gid(e['recipe']) for e in (t.get('effects') or []) if e['type'] == 'unlock-recipe']
    effs = [x for x in (fmt_effect(e) for e in (t.get('effects') or [])) if x]
    ph = tech_phase(n, t)
    prereq = ', '.join(tech_id(p) for p in (t.get('prerequisites') or [])) or '-'
    total = f"{count * sum(a for _, a in packs)} cards, {num(count * u['time'])} lab-s" if count else '-'
    row = [tech_id(n), tech_display(n), prereq, f"{count}" if count else f"`{formula}`", short, cost_packs, num(u['time']),
           total, ', '.join(recs) or '-', '; '.join(effs) or '-', ('∞' if t.get('max_level') == 'infinite' else (t.get('max_level') or '-')),
           'yes' if n in rocket_req else '', ph]
    if t.get('max_level') == 'infinite' or formula:
        inf_rows.append(row)
    else:
        rows.append(row)

lines = ['# 04 — Technologies (Gearforge base set)\n']
lines.append('Source: Factorio 1.1.110 `base/prototypes/technology.lua` (normal mode), generated by `docs/research/tools/gen_techs.py`.\n')
lines.append('## Column meanings\n')
lines.append('- **cost count** – number of research units. `count_formula` for leveled/infinite techs uses `L` = level being researched (Factorio formula syntax; `^` = power).')
lines.append('- **cards** – per-unit ingredients (letters: R=mechanics(red), G=motion(green), K=defense(black), B=reaction(blue), P=fabrication(purple), Y=systems(yellow), W=orbital(white)). Every listed card is consumed ×amount per unit.')
lines.append('- **time/unit** – seconds per unit for one lab at speed 1. Wall time = count × time / Σ(lab speed × (1 + lab speed bonus) × (1 + module speed bonus)).')
lines.append('- **total** – total cards consumed and total lab-seconds (count × time).')
lines.append('- **rocket?** – "yes" if the tech is in the prerequisite closure of `rocket_silo` (must exist in MVP).')
lines.append('- **phase** – MVP or later phase (tech gated to the phase of what it unlocks). Later-phase techs that are rocket prerequisites remain researchable in MVP but only unlock their MVP-relevant recipes (e.g. `railway` unlocks `rail` needed for fabrication cards; locomotives stay locked until the trains phase).')
lines.append('- Techs named `X_N` are levels of a series; level N requires level N−1 (and is listed as a prerequisite).\n')
lines.append('### Effect modifier glossary\n')
gl = [
    ['inserter-stack-size-bonus', 'adds N to the hand size of non-stack inserters (base 1 → max 3)'],
    ['stack-inserter-capacity-bonus', 'adds N to the hand size of stack inserters (base 1 → max 12)'],
    ['mining-drill-productivity-bonus', '+X% mining productivity for all drills of the force (additive)'],
    ['laboratory-speed', '+X% lab research speed (additive)'],
    ['character-inventory-slots-bonus', '+N main inventory slots'],
    ['worker-robot-speed', '+X% robot speed (additive)'], ['worker-robot-storage', '+N robot cargo size'],
    ['worker-robot-battery', '+X% robot battery'], ['train-braking-force-bonus', '+X% train braking force'],
    ['character-logistic-requests / trash-slots', 'enable personal logistics slots (robots phase)'],
    ['ghost-time-to-live', 'ghosts of destroyed entities persist (seconds in ticks) – robots phase'],
    ['maximum-following-robots-count', '+N combat robots following the player'],
    ['ammo-damage / gun-speed / turret-attack', 'combat phase damage & fire-rate modifiers (category in brackets)'],
    ['artillery-range', '+X% artillery range'],
]
lines.append(md_table(['modifier', 'meaning'], gl))
lines.append('')
lines.append(f'## Finite technologies ({len(rows)})\n')
lines.append('Sorted by number of card types, then unit count.\n')
lines.append(md_table(['id', 'name', 'prerequisites', 'cost count', 'cards', 'per unit', 'time/unit s', 'total', 'unlocks recipes', 'effects', 'max lvl', 'rocket?', 'phase'], rows))
lines.append('')
lines.append(f'## Leveled / infinite technologies ({len(inf_rows)})\n')
lines.append('Rows with a `count_formula`. `max lvl` ∞ = infinite (keeps increasing). For the infinite rows the formula applies from the first level shown up to infinity.\n')
lines.append(md_table(['id', 'name', 'prerequisites', 'cost count', 'cards', 'per unit', 'time/unit s', 'total', 'unlocks recipes', 'effects', 'max lvl', 'rocket?', 'phase'], inf_rows))
lines.append('')
lines.append('## Infinite research summary\n')
inf = [[tech_id(n), tech_display(re.sub(r'-\d+$', '', n)), f"`{unit(techdata(t))['count_formula']}`", ''.join(PACK_SHORT[p] for p, a in ingr(unit(techdata(t)))), num(unit(techdata(t))['time']),
        '; '.join(x for x in (fmt_effect(e) for e in t.get('effects', [])) if x), tech_phase(n, techdata(t))]
       for n, t in sorted(T.items()) if techdata(t).get('max_level') == 'infinite']
lines.append(md_table(['first infinite level id', 'series', 'cost formula (L = level)', 'cards', 'time/unit s', 'effect per level', 'phase'], inf))
lines.append('\nAll infinite techs require orbital (white) cards → they become available only after the first satellite launch. Cost examples: mining productivity level L costs 2500×(L−3) units (L=4: 2500; L=10: 17 500). Worker robot speed 1000×2^(L−6). Weapon-damage series: 1000×2^(L−7) (L=7: 1000; L=8: 2000; L=9: 4000). Artillery range: 1000×2^L (L=1: 2000). Artillery speed: 1000+1000×3^(L−1) (L=1: 2000; L=2: 4000; L=3: 10 000). Follower robot count: 100(L−6)+900 (L=7: 1000).\n\n### Rocket-critical technologies\n\nThe 38 technologies in the prerequisite closure of `rocket_silo` (all must be in MVP): ' + ', '.join(sorted(tech_id(x) for x in rocket_req)) + '.\n')
lines.append(f'**Totals:** {len(T)} technology prototypes ({len(rows)} finite, {len(inf_rows)} leveled/infinite-series prototypes; {len(inf)} truly infinite).\n')
with open(OUT, 'w') as f:
    f.write('\n'.join(lines))
print('techs', len(T), 'finite', len(rows), 'leveled', len(inf_rows), 'infinite', len(inf), 'rocket closure', len(rocket_req))
